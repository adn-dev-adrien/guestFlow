#!/usr/bin/env node
// The refund write-path replay of the price gate (specs/pricing-components.md §3 rule 81, decision D9).
//
//   node scripts/price-gate/buildWriteReplay.mjs --out server/src/tests/fixtures/price-gate/writes.json
//
// RUN IT ON A WORKTREE OF THE `price-gate-baseline` TAG, never on the branch under test: the expected figures are the
// ones the original code writes, captured once (see README.md, « Capture procedure »; copy `scripts/price-gate/` and
// `server/src/tests/helpers/` into the worktree as the procedure says). Plays the cases of `writeReplay.js` on an
// empty in-memory database with the clock frozen on the capture day, and writes `{ meta, cases }`. Prints case names
// and step counts only.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const CAPTURED_AT = '2026-11-11T12:00:00+01:00';

const args = process.argv.slice(2);
const out = args.includes('--out') ? args[args.indexOf('--out') + 1] : null;
if (!out) {
  console.error('usage: buildWriteReplay.mjs --out <writes.json>   (on a worktree of the price-gate-baseline tag)');
  process.exit(2);
}

process.env.DB_PATH = ':memory:';
process.env.TZ = 'Europe/Paris';
const { freezeClock } = require(path.join(root, 'server/src/tests/vatRegimeGoldenFixture.js'));
freezeClock(new Date(CAPTURED_AT));
const { playWrites } = require(path.join(root, 'scripts/price-gate/writeReplay.js'));

const cases = await playWrites();
const meta = { capturedAt: CAPTURED_AT, note: 'captured once on the price-gate-baseline code; never regenerated by PR A, B or C' };
fs.mkdirSync(path.dirname(path.resolve(out)), { recursive: true });
fs.writeFileSync(out, `${JSON.stringify({ meta, cases }, null, 1)}\n`);
for (const [name, played] of Object.entries(cases)) console.log(`${name}: ${played.steps.length} steps`);
process.exit(0);
