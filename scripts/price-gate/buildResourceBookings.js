#!/usr/bin/env node
/**
 * The figures of the standalone resource bookings and of the platform price grids of the production copy (specs/pricing-components.md §3 rule 68).
 *
 *   DB_PATH=:memory: node scripts/price-gate/buildResourceBookings.js <capturedAt ISO> <inputs.json> <out.json>
 *
 * Loads the anonymised rows of `inputs.json` into a fresh database — the one the gate itself loads, whose
 * `resource_bookings` table carries every column of the plugin's migrations, which a production copy may lack — and
 * writes `{ resourceBookings: { [bookingId]: figures }, propertyGrids: { [propertyId]: figures } }` (`recompute.js` `recomputeResourceBookings`, `recomputePropertyGrids`). Run by `buildFixture.mjs` on the
 * baseline code, in a process of its own; never regenerated by PR A, B or C. Prints the number of bookings only.
 */
const fs = require('node:fs');
const path = require('node:path');

const [capturedAt, inputsFile, outFile] = process.argv.slice(2);
if (!capturedAt || !inputsFile || !outFile || process.env.DB_PATH !== ':memory:') {
  console.error('usage: DB_PATH=:memory: buildResourceBookings.js <capturedAt ISO> <inputs.json> <out.json>');
  process.exit(2);
}
process.env.TZ = 'Europe/Paris';
const root = path.resolve(__dirname, '..', '..');
const { freezeClock } = require(path.join(root, 'server/src/tests/vatRegimeGoldenFixture.js'));
freezeClock(new Date(capturedAt));

const print = console.log;
console.log = () => {};
const inputs = JSON.parse(fs.readFileSync(inputsFile, 'utf8'));
const db = require(path.join(root, 'server/src/database.js'));
const { loadInputs, recomputeResourceBookings, recomputePropertyGrids } = require('./recompute.js');
loadInputs(db, inputs);
const bookings = recomputeResourceBookings(db);
const propertyGrids = recomputePropertyGrids(db);
fs.writeFileSync(outFile, `${JSON.stringify({ resourceBookings: bookings, propertyGrids }, null, 1)}\n`);
console.log = print;
print(`${Object.keys(bookings).length} resource bookings, ${Object.keys(propertyGrids).length} property grids`);
