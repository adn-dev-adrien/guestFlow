#!/usr/bin/env node
/**
 * The synthetic refund stays of the price gate (specs/pricing-components.md §3 rules 68 and 72, PR A bullet).
 *
 *   DB_PATH=:memory: node scripts/price-gate/buildSynthetic.js <capturedAt ISO> <out.json>
 *
 * The production snapshot holds one refund. The refund cases the test suites pin (cancelled with indemnity, caisse
 * interne, mixed methods, installments, line refund, trop-perçu) are therefore played here through the real
 * controllers on an empty in-memory database, with the shared fixture of the suites (`moneyLedgerFixture.js`: its
 * properties, platforms and the create / payment mark / cancel / refund / save moves). Their rows are copied by the
 * same allow-list as the production copy and their figures are those of the code that ran them.
 *
 * Every other money path the snapshot holds no example of is played here too, one named case each (rule 68): a 7.77 %
 * discount, the progressive option fresh and sold, the insurance on the stay and per night, typed counts, mid-stay
 * notes settled in cash and on the books, the arrival reduction and tip, a platform penalty, a complement paid in a
 * split, a live installment plan, and the standalone and attached hourly bookings. A figure is read from the code that
 * ran the case, never written by hand.
 *
 * Writes { cases, resourceBookingCases, tables, stays, resourceBookings, propertyGrids, intakes } to <out.json>: the case → stay id map, the anonymised rows,
 * `{ [reservationId]: figures }` (each read at the four instants of `recompute.js`), the figures of the resource
 * bookings and the crafted platform intakes with what their replay produced. Prints ids only. Like the production capture it runs on the `price-gate-baseline`
 * code and is never regenerated by PR A, B or C.
 */
