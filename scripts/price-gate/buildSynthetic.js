async function play() {
  // 1. Cancelled with indemnity: acompte and solde collected, the retained avoir and the indemnity (D3).
  {
    const stay = fiche(WITH_ACOMPTE, 'direct');
    pay(stay.id, D, S);
    await cancel(stay.id);
    cases['cancelled-indemnity'] = stay.id;
  }
  // 2. The same, then half of the first line given back by transfer (a refund after the cancellation).
  {
    const stay = fiche(WITH_ACOMPTE, 'direct');
    pay(stay.id, D, S);
    await cancel(stay.id);
    refundFirstLineHalf(stay.id);
    cases['cancelled-half-given-back'] = stay.id;
  }
  // 3. The same, everything the register offers given back (book money by transfer).
  {
    const stay = fiche(WITH_ACOMPTE, 'direct');
    pay(stay.id, D, S);
    await cancel(stay.id);
    giveAll(stay.id);
    cases['cancelled-all-given-back'] = stay.id;
  }
  // 4. Caisse interne: solde collected in the caisse, never requalified (D8), cash given back in the caisse only.
  {
    const stay = fiche(NO_ACOMPTE, 'direct');
    payTenders(stay.id, 'balance', [cashIn(cents(rowOf(stay.id).balanceAmount))]);
    await cancel(stay.id);
    giveAll(stay.id);
    cases['caisse-interne-cancelled'] = stay.id;
  }
  // 5. Mixed methods: an acompte on the books (card + transfer), a solde split caisse / card, then a line refund.
  {
    const stay = fiche(WITH_ACOMPTE, 'direct');
    const deposit = cents(rowOf(stay.id).depositAmount);
    payTenders(stay.id, 'deposit', [card(5000), transfer(deposit - 5000)]);
    const balance = cents(rowOf(stay.id).balanceAmount);
    payTenders(stay.id, 'balance', [cashIn(10000), card(balance - 10000)]);
    refundFirstLineHalf(stay.id);
    cases['mixed-methods-line-refund'] = stay.id;
  }
  // 6. Mixed methods, cancelled: the acompte kept whole, the solde's caisse share given back in the caisse.
  {
    const stay = fiche(WITH_ACOMPTE, 'direct');
    const deposit = cents(rowOf(stay.id).depositAmount);
    payTenders(stay.id, 'deposit', [card(5000), transfer(deposit - 5000)]);
    const balance = cents(rowOf(stay.id).balanceAmount);
    payTenders(stay.id, 'balance', [cashIn(10000), card(balance - 10000)]);
    await cancel(stay.id);
    giveAll(stay.id);
    cases['mixed-methods-cancelled'] = stay.id;
  }
  // 7. Installments: a three-part plan, two parts paid, cancelled (each bucket reversed on its frozen split).
  {
    const stay = fiche(NO_ACOMPTE, 'direct');
    const row = rowOf(stay.id);
    const total = cents(row.finalPrice) + cents(row.touristTaxTotal);
    const third = Math.floor(total / 3);
    const plan = installmentsModel.replacePlan(stay.id, [
      { number: 1, dueDate: inDays(1), amountCents: third },
      { number: 2, dueDate: inDays(20), amountCents: third },
      { number: 3, dueDate: inDays(40), amountCents: total - 2 * third },
    ], total);
    plan.slice(0, 2).forEach((i) => recordInstallmentPayment({ db }, { installmentId: i.id, paidDate: TODAY, method: 'transfer' }));
    await cancel(stay.id);
    cases['installments-cancelled'] = stay.id;
  }
  // 8. Installments on a live stay, one refund on a line.
  {
    const stay = fiche(NO_ACOMPTE, 'direct');
    const row = rowOf(stay.id);
    const total = cents(row.finalPrice) + cents(row.touristTaxTotal);
    const half = Math.floor(total / 2);
    const plan = installmentsModel.replacePlan(stay.id, [
      { number: 1, dueDate: inDays(1), amountCents: half },
      { number: 2, dueDate: inDays(30), amountCents: total - half },
    ], total);
    plan.slice(0, 1).forEach((i) => recordInstallmentPayment({ db }, { installmentId: i.id, paidDate: TODAY, method: 'transfer' }));
    refundFirstLineHalf(stay.id);
    cases['installments-line-refund'] = stay.id;
  }
  // 9. Line refund on a live stay fully paid, by transfer.
  {
    const stay = fiche(WITH_ACOMPTE, 'direct');
    pay(stay.id, D, S);
    refundFirstLineHalf(stay.id);
    cases['line-refund-live'] = stay.id;
  }
  // 10. Trop-perçu: a paid stay shortened, the stored over-collection, then the stored over-collection read.
  {
    const stay = fiche(WITH_ACOMPTE, 'direct');
    pay(stay.id, D, S);
    await put(stay, { endDate: inDays(dayOffset(stay.body.startDate) + 1) });
    cases['overpayment-shortened'] = stay.id;
  }
  // 11. A platform stay (own channel taking an acompte), paid and cancelled.
  {
    const stay = fiche(WITH_ACOMPTE, PLATFORM.ownReversed);
    pay(stay.id, D, S);
    await cancel(stay.id);
    cases['platform-own-cancelled'] = stay.id;
  }
  catalogue();
  await playMoneyPaths();
}

