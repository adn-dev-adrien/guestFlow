const cents = (euros) => Math.round(Number(euros) * 100);
const cashIn = (amountCents) => ({ method: 'cash', amountCents, internal: true });
const card = (amountCents) => ({ method: 'card', amountCents, internal: false });
const transfer = (amountCents) => ({ method: 'transfer', amountCents, internal: false });
const ok = (res, what) => {
  if (res.statusCode !== 200 && res.statusCode !== 201) throw new Error(`${what} failed: ${JSON.stringify(res.body)}`);
  return res;
};

// Half of what the register offers on its first line that offers anything.
function refundFirstLineHalf(id, method = 'transfer') {
  const line = register(id).refundableLines.find((l) => l.refundableTtc > 0);
  if (!line) throw new Error(`stay ${id}: the register offers nothing`);
  return ok(refund(id, [{ key: line.key, amountTtc: Math.round(line.refundableTtc * 50) / 100 }], method), 'refund');
}

const payTenders = (id, bucket, tenders) => {
  const row = rowOf(id);
  const amount = bucket === 'deposit' ? row.depositAmount : row.balanceAmount;
  return ok(mark(id, { [`${bucket}Paid`]: true, [`${bucket}PaidDate`]: TODAY, expectedAmountCents: cents(amount), tenders }), `${bucket} mark`);
};

const cases = {};
