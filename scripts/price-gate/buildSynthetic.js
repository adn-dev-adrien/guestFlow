async function playMoneyPaths() {
  // 12. A discount with two decimals, on a stay with a stay-priced extra.
  {
    const stay = fiche(WITH_ACOMPTE, 'direct', { discountPercent: 7.77, options: [{ optionId: 107, quantity: 1 }], selectedOptions: [{ optionId: 107, quantity: 1 }] });
    cases['discount-7.77pct'] = stay.id;
  }
  // 13. The progressive option. A line keeps the price it was sold at while its units are unchanged, so the gate only
  //     sees the family price on a line stored with no price and no unit price (fresh); a sold line is stored priced, the tiers then move
  //     in the catalogue and the line must keep its snapshot.
  {
    // Three participants at 10 + 8 + 7 = 25: the average (8.33) moves by a cent for a cent more on the total.
    const line = { optionId: 108, quantity: 3 };
    const stay = fiche(NO_ACOMPTE, 'direct', { options: [line], selectedOptions: [line] });
    db.prepare('UPDATE reservation_options SET totalPrice = 0, unitPrice = 0 WHERE reservationId = ? AND optionId = 108').run(stay.id);
    cases['progressive-option-fresh'] = stay.id;
  }
  {
    const line = { optionId: 101, quantity: 4 };
    const stay = fiche(WITH_ACOMPTE, 'direct', { options: [line], selectedOptions: [line] });
    pay(stay.id, D);
    db.prepare('UPDATE reservation_options SET sasArrivalOrigin = 1 WHERE reservationId = ? AND optionId = 101').run(stay.id);
    db.prepare('UPDATE options SET optionProgressiveTiers = ? WHERE id = 101')
      .run(JSON.stringify([{ participantNumber: 1, unitPrice: 10 }, { participantNumber: 2, unitPrice: 8.15 }, { participantNumber: 3, unitPrice: 6.35 }]));
    cases['progressive-option-sold'] = stay.id;
  }
  // 14. The insurance on the stay (percent) and the insurance per night with a price.
  {
    const line = { optionId: 102, quantity: 1 };
    cases['percent-of-stay-insurance'] = fiche(WITH_ACOMPTE, 'direct', { options: [line], selectedOptions: [line] }).id;
  }
  {
    const line = { optionId: 103, quantity: 1 };
    cases['per-night-insurance-priced'] = fiche(NO_ACOMPTE, 'direct', { options: [line], selectedOptions: [line] }).id;
  }
  // 15. Per-night and per-person-per-night extras with typed counts (3 nights typed on a 2-night stay, 5 people on 2 adults).
  {
    const lines = [{ optionId: 104, quantity: 1, cardNights: 3 }, { optionId: 105, quantity: 1, cardPersons: 5 }, { optionId: 106, quantity: 2, cardPersons: 3 }];
    cases['typed-counts-options'] = fiche(WITH_ACOMPTE, 'direct', { options: lines, selectedOptions: lines, forceTypedCounts: true }).id;
  }
  // 16. Mid-stay notes settled, once in the caisse and once on the books: both extras were sold after the arrival (an
  //     empty baseline makes every extra line a mid-stay one), one is collected whole, the other in part.
  for (const [name, cash] of [['mid-stay-notes-settled-cash', true], ['mid-stay-notes-settled-book', false]]) {
    const lines = [{ optionId: 107, quantity: 1 }, { optionId: 104, quantity: 1 }];
    const stay = fiche(WITH_ACOMPTE, 'direct', { options: lines, selectedOptions: lines });
    pay(stay.id, D, S);
    db.prepare("UPDATE reservations SET arrivalExtrasBaseline = '{}', checkInDone = 1 WHERE id = ?").run(stay.id);
    reservationsModel.syncMidStayComplement(stay.id, [
      { label: 'Per stay', unitPrice: 33.33, amount: 33.33, key: 'opt:107', source: MID_STAY_SOURCE },
      { label: 'Per night', unitPrice: 7.33, amount: 14.66, key: 'opt:104', source: MID_STAY_SOURCE },
    ]);
    reservationsModel.settleMidStayNote(stay.id, { items: [{ key: 'opt:107', amount: 33.33 }, { key: 'opt:104', amount: 10.01 }], cash });
    cases[name] = stay.id;
  }
  // 17. One payment at the door with a reduction and a tip.
  {
    const stay = fiche(WITH_ACOMPTE, 'direct');
    pay(stay.id, D, S);
    db.prepare('UPDATE reservations SET arrivalPaymentGroup = ?, arrivalPaymentReduction = 12.34, arrivalPaymentTip = 5.67 WHERE id = ?')
      .run(JSON.stringify({ at: TODAY, cash: 0, total: 100, buckets: ['deposit', 'balance'] }), stay.id);
    cases['arrival-reduction-and-tip'] = stay.id;
  }
  // 18. A platform stay with a declared penalty.
  {
    const stay = fiche(NO_ACOMPTE, PLATFORM.reversed, { platformGrossAmount: 700, platformPayoutAmount: 560.5, platformCommissionAmount: 139.5 });
    pay(stay.id, S);
    db.prepare('UPDATE reservations SET platformPenaltyAmount = 23.45 WHERE id = ?').run(stay.id);
    cases['platform-penalty'] = stay.id;
  }
  // 19. A complement collected in a split (the split is stamped by the flip).
  {
    const stay = fiche(WITH_ACOMPTE, 'direct', { customOptions: [forced(50, 'Complement A'), forced(33.33, 'Complement B')] });
    pay(stay.id, D, S, C);
    cases['complement-paid-split'] = stay.id;
  }
  // 20. A live installment plan, one part paid, the stay not cancelled.
  {
    const stay = fiche(NO_ACOMPTE, 'direct');
    const row = rowOf(stay.id);
    const total = cents(row.finalPrice) + cents(row.touristTaxTotal);
    const third = Math.floor(total / 3);
    const plan = installmentsModel.replacePlan(stay.id, [
      { number: 1, dueDate: inDays(1), amountCents: third },
      { number: 2, dueDate: inDays(20), amountCents: third },
      { number: 3, dueDate: inDays(40), amountCents: total - 2 * third },
    ], total);
    plan.slice(0, 1).forEach((i) => recordInstallmentPayment({ db }, { installmentId: i.id, paidDate: TODAY, method: 'transfer' }));
    cases['installments-live'] = stay.id;
  }
  // 21. An own channel taking the acompte, both paid on the books with the commissions the channel withheld, the stay
  //     still live: cancelling it now would reverse them (rule 70).
  {
    const stay = fiche(WITH_ACOMPTE, PLATFORM.ownReversed);
    pay(stay.id, D, S);
    db.prepare('UPDATE reservations SET acompteCommissionAmount = 4.35, platformCommissionAmount = 12.7 WHERE id = ?').run(stay.id);
    cases['own-channel-commissions-live'] = stay.id;
  }
  playHourlyBookings();
  playIntakeStays();
}

// The `hourly-resources` plugin's own table, a resource priced per hour with an evening band and external rates, and
// three bookings on it: a standalone one paid in two parts (the external grid, VAT 20 %), a standalone one still
// unpaid with offered time, and one attached to a stay (the stay's grid and VAT).
function playHourlyBookings() {
  applyPluginSchema(db, 'hourly-resources');
  const version = JSON.parse(fs.readFileSync(path.join(serverSrc, 'plugins', 'hourly-resources', 'manifest.json'), 'utf8')).version;
  db.prepare('INSERT OR REPLACE INTO plugins (id, enabled, version) VALUES (?, 1, ?)').run('hourly-resources', version);
  db.prepare(`INSERT INTO resources (id, name, quantity, price, priceType, isComplex, slotDuration, openTime, closeTime, showsPlanningCard, minimumUsageMinutes,
      hourlyEveningStart, hourlyEveningRate, hourlyExternalDayRate, hourlyExternalEveningRate)
    VALUES (301, 'Hourly', 2, 22.5, 'per_hour', 0, 60, '08:00', '23:00', 1, 60, '18:00', 31.5, 27.3, 38.9)`).run();
  [NO_ACOMPTE, WITH_ACOMPTE].forEach((propertyId) => db.prepare('INSERT INTO resource_properties (resourceId, propertyId) VALUES (301, ?)').run(propertyId));
  db.prepare('INSERT INTO property_resource_prices (propertyId, resourceId, price, freeMinutes) VALUES (?, 301, 19.75, 30)').run(WITH_ACOMPTE);
  const bookings = require(path.join(serverSrc, 'plugins', 'hourly-resources', 'bookingsModel.js')).create(db, { standaloneVatRate: () => 20 });
  const book = (draft) => {
    const made = bookings.createBooking({ resourceId: 301, ...draft });
    if (!made.ok) throw new Error(`booking failed: ${JSON.stringify(made)}`);
    return Number(made.id);
  };
  const day = (n) => inDays(n);
  const paidOnce = book({ date: day(10), startTime: '17:00', endTime: '20:00' });
  const paid = bookings.recordPayment(paidOnce, { tenders: [{ method: 'card', amountCents: 5000, internal: false }, { method: 'cash', amountCents: Math.round(bookings.rawById(paidOnce).totalPrice * 100) - 5000, internal: true }], paidAt: TODAY });
  if (!paid.ok) throw new Error(`booking payment failed: ${JSON.stringify(paid)}`);
  resourceBookingCases['standalone-hourly-booking-paid-20pct'] = paidOnce;
  resourceBookingCases['standalone-hourly-booking-flat'] = book({ date: day(12), startTime: '09:00', endTime: '11:30' });
  resourceBookingCases['standalone-hourly-booking-offered'] = book({ date: day(11), startTime: '19:00', endTime: '21:00', offeredMinutes: 30 });
  const stay = fiche(WITH_ACOMPTE, 'direct');
  // No screen links a booking to a stay any more (rule 46); a row stored that way before is still priced, with the stay's grid and VAT.
  const attached = book({ date: rowOf(stay.id).startDate, startTime: '10:00', endTime: '12:15', propertyId: WITH_ACOMPTE });
  db.prepare('UPDATE resource_bookings SET reservationId = ? WHERE id = ?').run(stay.id, attached);
  cases['stay-with-hourly-booking'] = stay.id;
  resourceBookingCases['hourly-booking-attached-to-a-stay'] = attached;
}

// Booking- and Airbnb-shaped intakes on synthetic platform stays, each carrying one line routed to the arrival
