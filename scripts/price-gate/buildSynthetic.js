#!/usr/bin/env node
/**
 * The synthetic refund stays of the price gate (specs/pricing-components.md §3 rules 68 and 72, PR A bullet).
 *
 *   DB_PATH=:memory: node scripts/price-gate/buildSynthetic.js <capturedAt ISO> <out.json>
 *
 * The production snapshot holds one refund. The refund cases the test suites pin (cancelled with indemnity, caisse
 * interne, mixed methods, installments, line refund, trop-perçu) are therefore played here through the real
 * controllers on an empty in-memory database, with the shared fixture of the suites (`moneyLedgerFixture.js`: its
 * properties, platforms and the create / payment mark / cancel / refund / save moves). Their rows are copied by the
 * same allow-list as the production copy and their figures are those of the code that ran them.
 *
 * Writes { cases, tables, stays } to <out.json>: the case → stay id map, the anonymised rows and
 * `{ [reservationId]: figures }`. Prints ids only. Like the production capture it runs on the `price-gate-baseline`
 * code and is never regenerated by PR A, B or C.
 */
const fs = require('node:fs');
const path = require('node:path');

const [capturedAt, outFile] = process.argv.slice(2);
if (!capturedAt || !outFile) {
  console.error('usage: buildSynthetic.js <capturedAt ISO> <out.json>   (DB_PATH=:memory:)');
  process.exit(2);
}
if (process.env.DB_PATH !== ':memory:') {
  console.error('refused: the synthetic stays are played on an empty in-memory database (DB_PATH=:memory:)');
  process.exit(2);
}
process.env.TZ = 'Europe/Paris';

const root = path.resolve(__dirname, '..', '..');
const serverSrc = path.join(root, 'server', 'src');
const { freezeClock } = require(path.join(serverSrc, 'tests', 'vatRegimeGoldenFixture.js'));
freezeClock(new Date(capturedAt));

const print = console.log;
console.log = () => {};
const money = require(path.join(serverSrc, 'tests', 'moneyLedgerFixture.js'));
const { anonymise, ALLOW_LIST } = require('./anonymise.js');
const { recomputeStays } = require('./recompute.js');
const installmentsModel = require(path.join(serverSrc, 'models', 'installmentsModel.js'));
const { recordInstallmentPayment } = require(path.join(serverSrc, 'utils', 'installmentPayment.js'));

const {
  db, TODAY, NO_ACOMPTE, WITH_ACOMPTE, PLATFORM, S, D, fiche, put, pay, cancel, register, refund, giveAll, rowOf, inDays, mark,
} = money;

const cents = (euros) => Math.round(Number(euros) * 100);
const cashIn = (amountCents) => ({ method: 'cash', amountCents, internal: true });
const card = (amountCents) => ({ method: 'card', amountCents, internal: false });
const transfer = (amountCents) => ({ method: 'transfer', amountCents, internal: false });
const ok = (res, what) => {
  if (res.statusCode !== 200 && res.statusCode !== 201) throw new Error(`${what} failed: ${JSON.stringify(res.body)}`);
  return res;
};

// Half of what the register offers on its first line that offers anything.
function refundFirstLineHalf(id, method = 'transfer') {
  const line = register(id).refundableLines.find((l) => l.refundableTtc > 0);
  if (!line) throw new Error(`stay ${id}: the register offers nothing`);
  return ok(refund(id, [{ key: line.key, amountTtc: Math.round(line.refundableTtc * 50) / 100 }], method), 'refund');
}

const payTenders = (id, bucket, tenders) => {
  const row = rowOf(id);
  const amount = bucket === 'deposit' ? row.depositAmount : row.balanceAmount;
  return ok(mark(id, { [`${bucket}Paid`]: true, [`${bucket}PaidDate`]: TODAY, expectedAmountCents: cents(amount), tenders }), `${bucket} mark`);
};

const cases = {};

async function play() {
  // 1. Cancelled with indemnity: acompte and solde collected, the retained avoir and the indemnity (D3).
  {
    const stay = fiche(WITH_ACOMPTE, 'direct');
    pay(stay.id, D, S);
    await cancel(stay.id);
    cases['cancelled-indemnity'] = stay.id;
  }
  // 2. The same, then half of the first line given back by transfer (a refund after the cancellation).
  {
    const stay = fiche(WITH_ACOMPTE, 'direct');
    pay(stay.id, D, S);
    await cancel(stay.id);
    refundFirstLineHalf(stay.id);
    cases['cancelled-half-given-back'] = stay.id;
  }
  // 3. The same, everything the register offers given back (book money by transfer).
  {
    const stay = fiche(WITH_ACOMPTE, 'direct');
    pay(stay.id, D, S);
    await cancel(stay.id);
    giveAll(stay.id);
    cases['cancelled-all-given-back'] = stay.id;
  }
  // 4. Caisse interne: solde collected in the caisse, never requalified (D8), cash given back in the caisse only.
  {
    const stay = fiche(NO_ACOMPTE, 'direct');
    payTenders(stay.id, 'balance', [cashIn(cents(rowOf(stay.id).balanceAmount))]);
    await cancel(stay.id);
    giveAll(stay.id);
    cases['caisse-interne-cancelled'] = stay.id;
  }
  // 5. Mixed methods: an acompte on the books (card + transfer), a solde split caisse / card, then a line refund.
  {
    const stay = fiche(WITH_ACOMPTE, 'direct');
    const deposit = cents(rowOf(stay.id).depositAmount);
    payTenders(stay.id, 'deposit', [card(5000), transfer(deposit - 5000)]);
    const balance = cents(rowOf(stay.id).balanceAmount);
    payTenders(stay.id, 'balance', [cashIn(10000), card(balance - 10000)]);
    refundFirstLineHalf(stay.id);
    cases['mixed-methods-line-refund'] = stay.id;
  }
  // 6. Mixed methods, cancelled: the acompte kept whole, the solde's caisse share given back in the caisse.
  {
    const stay = fiche(WITH_ACOMPTE, 'direct');
    const deposit = cents(rowOf(stay.id).depositAmount);
    payTenders(stay.id, 'deposit', [card(5000), transfer(deposit - 5000)]);
    const balance = cents(rowOf(stay.id).balanceAmount);
    payTenders(stay.id, 'balance', [cashIn(10000), card(balance - 10000)]);
    await cancel(stay.id);
    giveAll(stay.id);
    cases['mixed-methods-cancelled'] = stay.id;
  }
  // 7. Installments: a three-part plan, two parts paid, cancelled (each bucket reversed on its frozen split).
  {
    const stay = fiche(NO_ACOMPTE, 'direct');
    const row = rowOf(stay.id);
    const total = cents(row.finalPrice) + cents(row.touristTaxTotal);
    const third = Math.floor(total / 3);
    const plan = installmentsModel.replacePlan(stay.id, [
      { number: 1, dueDate: inDays(1), amountCents: third },
      { number: 2, dueDate: inDays(20), amountCents: third },
      { number: 3, dueDate: inDays(40), amountCents: total - 2 * third },
    ], total);
    plan.slice(0, 2).forEach((i) => recordInstallmentPayment({ db }, { installmentId: i.id, paidDate: TODAY, method: 'transfer' }));
    await cancel(stay.id);
    cases['installments-cancelled'] = stay.id;
  }
  // 8. Installments on a live stay, one refund on a line.
  {
    const stay = fiche(NO_ACOMPTE, 'direct');
    const row = rowOf(stay.id);
    const total = cents(row.finalPrice) + cents(row.touristTaxTotal);
    const half = Math.floor(total / 2);
    const plan = installmentsModel.replacePlan(stay.id, [
      { number: 1, dueDate: inDays(1), amountCents: half },
      { number: 2, dueDate: inDays(30), amountCents: total - half },
    ], total);
    plan.slice(0, 1).forEach((i) => recordInstallmentPayment({ db }, { installmentId: i.id, paidDate: TODAY, method: 'transfer' }));
    refundFirstLineHalf(stay.id);
    cases['installments-line-refund'] = stay.id;
  }
  // 9. Line refund on a live stay fully paid, by transfer.
  {
    const stay = fiche(WITH_ACOMPTE, 'direct');
    pay(stay.id, D, S);
    refundFirstLineHalf(stay.id);
    cases['line-refund-live'] = stay.id;
  }
  // 10. Trop-perçu: a paid stay shortened, the stored over-collection, then the stored over-collection read.
  {
    const stay = fiche(WITH_ACOMPTE, 'direct');
    pay(stay.id, D, S);
    await put(stay, { endDate: inDays(dayOffset(stay.body.startDate) + 1) });
    cases['overpayment-shortened'] = stay.id;
  }
  // 11. A platform stay (own channel taking an acompte), paid and cancelled.
  {
    const stay = fiche(WITH_ACOMPTE, PLATFORM.ownReversed);
    pay(stay.id, D, S);
    await cancel(stay.id);
    cases['platform-own-cancelled'] = stay.id;
  }
}

function dayOffset(iso) {
  const days = (Date.parse(`${iso}T00:00:00Z`) - Date.parse(`${TODAY}T00:00:00Z`)) / 86400000;
  return Math.round(days);
}

play().then(() => {
  const source = {};
  const present = new Set(db.prepare("SELECT name FROM sqlite_master WHERE type = 'table'").all().map((r) => r.name));
  for (const table of Object.keys(ALLOW_LIST)) {
    if (present.has(table)) source[table] = db.prepare(`SELECT * FROM ${table} ORDER BY rowid`).all();
  }
  const copied = anonymise(source);
  const intakes = ['booking_intakes', 'airbnb_intakes', 'gdf_intakes'];
  const tables = Object.fromEntries(Object.entries(copied).filter(([t]) => !intakes.includes(t)).sort(([a], [b]) => a.localeCompare(b)));
  const stays = recomputeStays(db);
  fs.writeFileSync(outFile, `${JSON.stringify({ cases, tables, stays }, null, 1)}\n`);
  console.log = print;
  print(`synthetic stays: ${Object.entries(cases).map(([name, id]) => `${name}=${id}`).join(', ')}`);
}).catch((err) => {
  console.log = print;
  console.error(err.stack || err);
  process.exit(1);
});
